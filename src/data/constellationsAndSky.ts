export interface CatalogStar {
  id: string;
  name: string;
  bayer: string;
  constellationId: string;
  raHours: number; // J2000 Right Ascension (0..24)
  decDeg: number;  // J2000 Declination (-90..+90)
  mag: number;     // Apparent V magnitude
  distanceLy: number;
  spectralType: string;
  colorHex: string;
  summary: string;
}

